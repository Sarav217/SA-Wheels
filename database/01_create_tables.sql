-- Public Transport Bus Ticketing System
-- Oracle Database 21c XE schema creation script.
-- Run this script first from SQL*Plus.

-- USERS stores both normal passengers and the user account associated with an admin.
CREATE TABLE users (
    user_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    full_name     VARCHAR2(100) NOT NULL,
    email         VARCHAR2(150) NOT NULL,
    password      VARCHAR2(100) NOT NULL,
    phone_number  VARCHAR2(20),
    created_at    DATE DEFAULT SYSDATE NOT NULL,
    user_status   VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_status CHECK (user_status IN ('ACTIVE', 'INACTIVE'))
);

-- ADMIN identifies which user accounts have administrator privileges.
CREATE TABLE admin (
    admin_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    user_id       NUMBER NOT NULL,
    admin_role    VARCHAR2(30) DEFAULT 'ADMIN' NOT NULL,
    created_at    DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_admin PRIMARY KEY (admin_id),
    CONSTRAINT uq_admin_user UNIQUE (user_id),
    CONSTRAINT fk_admin_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

-- ROUTES contains source/destination pairs, schedules, and fares.
-- DATE stores both the schedule date and time portion.
CREATE TABLE routes (
    route_id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    route_number      VARCHAR2(20) NOT NULL,
    source_location   VARCHAR2(100) NOT NULL,
    destination       VARCHAR2(100) NOT NULL,
    departure_time    DATE NOT NULL,
    arrival_time      DATE NOT NULL,
    fare              NUMBER(10, 2) NOT NULL,
    route_status      VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT pk_routes PRIMARY KEY (route_id),
    CONSTRAINT uq_routes_number UNIQUE (route_number),
    CONSTRAINT ck_routes_fare CHECK (fare >= 0),
    CONSTRAINT ck_routes_time CHECK (arrival_time > departure_time),
    CONSTRAINT ck_routes_status CHECK (route_status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT ck_routes_locations CHECK (source_location <> destination)
);

-- BOOKINGS connects a user to a selected route for a travel date.
CREATE TABLE bookings (
    booking_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    user_id         NUMBER NOT NULL,
    route_id        NUMBER NOT NULL,
    booking_date    DATE DEFAULT SYSDATE NOT NULL,
    travel_date     DATE NOT NULL,
    seat_number     VARCHAR2(10) NOT NULL,
    total_fare      NUMBER(10, 2) NOT NULL,
    booking_status  VARCHAR2(20) DEFAULT 'CONFIRMED' NOT NULL,
    CONSTRAINT pk_bookings PRIMARY KEY (booking_id),
    CONSTRAINT fk_bookings_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_bookings_route FOREIGN KEY (route_id) REFERENCES routes (route_id),
    CONSTRAINT uq_booking_seat UNIQUE (route_id, travel_date, seat_number),
    CONSTRAINT ck_bookings_fare CHECK (total_fare >= 0),
    CONSTRAINT ck_bookings_status CHECK (booking_status IN ('PENDING', 'CONFIRMED', 'CANCELLED'))
);

-- TICKETS has a one-to-one relationship with BOOKINGS.
CREATE TABLE tickets (
    ticket_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    booking_id      NUMBER NOT NULL,
    ticket_number   VARCHAR2(40) NOT NULL,
    qr_code         VARCHAR2(200) NOT NULL,
    issued_at       DATE DEFAULT SYSDATE NOT NULL,
    ticket_status   VARCHAR2(20) DEFAULT 'VALID' NOT NULL,
    CONSTRAINT pk_tickets PRIMARY KEY (ticket_id),
    CONSTRAINT uq_tickets_booking UNIQUE (booking_id),
    CONSTRAINT uq_tickets_number UNIQUE (ticket_number),
    CONSTRAINT uq_tickets_qr UNIQUE (qr_code),
    CONSTRAINT fk_tickets_booking FOREIGN KEY (booking_id) REFERENCES bookings (booking_id),
    CONSTRAINT ck_tickets_status CHECK (ticket_status IN ('VALID', 'USED', 'CANCELLED'))
);

-- INVOICES has a one-to-one relationship with BOOKINGS.
CREATE TABLE invoices (
    invoice_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    booking_id       NUMBER NOT NULL,
    invoice_number   VARCHAR2(40) NOT NULL,
    invoice_date     DATE DEFAULT SYSDATE NOT NULL,
    amount           NUMBER(10, 2) NOT NULL,
    payment_method   VARCHAR2(20) NOT NULL,
    payment_status   VARCHAR2(20) DEFAULT 'PAID' NOT NULL,
    CONSTRAINT pk_invoices PRIMARY KEY (invoice_id),
    CONSTRAINT uq_invoices_booking UNIQUE (booking_id),
    CONSTRAINT uq_invoices_number UNIQUE (invoice_number),
    CONSTRAINT fk_invoices_booking FOREIGN KEY (booking_id) REFERENCES bookings (booking_id),
    CONSTRAINT ck_invoices_amount CHECK (amount >= 0),
    CONSTRAINT ck_invoices_method CHECK (payment_method IN ('CASH', 'CARD', 'UPI', 'NET_BANKING')),
    CONSTRAINT ck_invoices_status CHECK (payment_status IN ('PENDING', 'PAID', 'REFUNDED'))
);

-- Confirm the tables created by this script.
SELECT table_name
FROM user_tables
WHERE table_name IN ('USERS', 'ADMIN', 'ROUTES', 'BOOKINGS', 'TICKETS', 'INVOICES')
ORDER BY table_name;

